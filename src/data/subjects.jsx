export function getSubject(subjectId) {
  return subjects.find((subject) => subject.id === subjectId) || null
}

export function getModule(subjectId, moduleId) {
  const subject = getSubject(subjectId)
  if (!subject || !moduleId) return null
  if (moduleId === 'lab' && subject.labHub) return subject.labHub
  return subject.modules.find((module) => module.id === moduleId)
    || subject.labPrograms?.find((module) => module.id === moduleId)
    || null
}
